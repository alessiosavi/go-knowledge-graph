func TestLockedFingerprintGolden(t *testing.T) {
	fp, err := Fingerprint(goldenText)
	if err != nil {
		t.Fatalf("Fingerprint: %v", err)
	}
	if fp.Version != 1 {
		t.Errorf("Version = %d, want locked 1 (re-check the GoGPUtils version and SignatureVersion before touching the pin)", fp.Version)
	}
	if fp.ExactKey != goldenExactKey {
		t.Errorf("ExactKey = %s, want locked %s", fp.ExactKey, goldenExactKey)
	}
	if !slices.Equal(fp.Sig, goldenSig) {
		t.Errorf("Sig = %v, want locked vector (re-check the GoGPUtils version before touching the pin)", fp.Sig)
	}
	if !slices.Equal(fp.Bands, goldenBands) {
		t.Errorf("Bands = %v, want locked vector (re-check the GoGPUtils version before touching the pin)", fp.Bands)
	}
}
